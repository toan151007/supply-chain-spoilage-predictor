"""
Read + workflow router for alerts.

Alerts are generated by the database function
`fn_generate_inventory_alerts()`, so this router does not accept POST.
What it does expose is the work a user performs on an alert: mark it read
and mark it resolved.

Database CHECK constraint `chk_alert_resolved_at` requires `resolved_at`
to be non-NULL exactly when `is_resolved` is TRUE. This router therefore
always sets both together - setting only the flag would be rejected by the
database with a confusing IntegrityError.
"""

from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy import func, select
from sqlalchemy.orm import Session, joinedload

from app.dependencies import require_role
from app.database import get_db
from app.models import Alert
from app.schemas.alert_schema import (
    AlertPage,
    AlertRead,
    MarkReadRequest,
    ResolveRequest,
)
from app.schemas.common import Message

router = APIRouter(prefix="/alerts", tags=["alerts"])

ALERT_TYPE_PATTERN = (
    "^(expiring_soon|expired|low_stock|over_stock|forecast_anomaly)$"
)
SEVERITY_PATTERN = "^(low|medium|high|critical)$"

# Most severe first, so ordering by severity puts critical on top.
SEVERITY_ORDER = ["critical", "high", "medium", "low"]


def _get_alert_or_404(db: Session, alert_id: int) -> Alert:
    alert = db.get(Alert, alert_id)
    if alert is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Alert {alert_id} not found",
        )
    return alert


def _paginate_alerts(
    db: Session, page: int, page_size: int, filters: list
) -> AlertPage:
    total = db.execute(
        select(func.count()).select_from(Alert).where(*filters)
    ).scalar_one()

    items = db.execute(
        select(Alert)
        .options(joinedload(Alert.store), joinedload(Alert.product))
        .where(*filters)
        .order_by(Alert.created_at.desc(), Alert.alert_id)
        .offset((page - 1) * page_size).limit(page_size)
    ).scalars().all()

    pages = (total + page_size - 1) // page_size
    return AlertPage(
        total=total, page=page, page_size=page_size, pages=pages, items=items
    )


# NOTE: `/unread` must be declared BEFORE `/{alert_id}`. FastAPI matches
# routes in order, and a path parameter typed `int` would try to parse
# "unread" as an integer and answer 422 instead of reaching this handler.
@router.get("/unread", response_model=AlertPage, summary="Unread alerts")
def list_unread_alerts(
    db: Session = Depends(get_db),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
    store_id: int | None = Query(None, gt=0),
    alert_type: str | None = Query(None, pattern=ALERT_TYPE_PATTERN),
    severity: str | None = Query(None, pattern=SEVERITY_PATTERN),
) -> AlertPage:
    """
    Alerts that have not been read yet.

    Unresolved alerts are included: "unread" and "unresolved" are separate
    ideas and the frontend may want each on its own.
    """
    filters = [Alert.is_read.is_(False)]
    if store_id is not None:
        filters.append(Alert.store_id == store_id)
    if alert_type is not None:
        filters.append(Alert.alert_type == alert_type)
    if severity is not None:
        filters.append(Alert.severity == severity)

    return _paginate_alerts(db, page, page_size, filters)


@router.get("/unread-count", summary="Count unread alerts")
def unread_count(
    db: Session = Depends(get_db),
    store_id: int | None = Query(None, gt=0),
    severity: str | None = Query(None, pattern=SEVERITY_PATTERN),
) -> dict:
    """
    Cheap unread counter for a notification badge.

    Returns counts split by severity as well, so the badge can show
    "3 unread, 1 critical" without fetching the rows.
    """
    filters = [Alert.is_read.is_(False)]
    if store_id is not None:
        filters.append(Alert.store_id == store_id)
    if severity is not None:
        filters.append(Alert.severity == severity)

    total = db.execute(
        select(func.count()).select_from(Alert).where(*filters)
    ).scalar_one()

    rows = db.execute(
        select(Alert.severity, func.count())
        .where(*filters)
        .group_by(Alert.severity)
    ).all()
    by_severity = {sev: 0 for sev in SEVERITY_ORDER}
    for sev, count in rows:
        by_severity[sev] = count

    return {"total": total, "by_severity": by_severity}


@router.get("", response_model=AlertPage, summary="List alerts")
def list_alerts(
    db: Session = Depends(get_db),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
    store_id: int | None = Query(None, gt=0),
    product_id: int | None = Query(None, gt=0),
    alert_type: str | None = Query(None, pattern=ALERT_TYPE_PATTERN),
    severity: str | None = Query(None, pattern=SEVERITY_PATTERN),
    is_read: bool | None = Query(None),
    is_resolved: bool | None = Query(None),
) -> AlertPage:
    """Paginated alert list with store, product, type, severity and state filters."""
    filters = []
    if store_id is not None:
        filters.append(Alert.store_id == store_id)
    if product_id is not None:
        filters.append(Alert.product_id == product_id)
    if alert_type is not None:
        filters.append(Alert.alert_type == alert_type)
    if severity is not None:
        filters.append(Alert.severity == severity)
    if is_read is not None:
        filters.append(Alert.is_read.is_(is_read))
    if is_resolved is not None:
        filters.append(Alert.is_resolved.is_(is_resolved))

    return _paginate_alerts(db, page, page_size, filters)


@router.get("/{alert_id}", response_model=AlertRead, summary="Get one alert")
def get_alert(alert_id: int, db: Session = Depends(get_db)) -> Alert:
    return _get_alert_or_404(db, alert_id)


@router.put(
    "/{alert_id}/read", response_model=AlertRead,
    summary="Mark an alert as read or unread",
 dependencies=[Depends(require_role('owner', 'manager', 'staff'))],)
def mark_read(
    alert_id: int, payload: MarkReadRequest, db: Session = Depends(get_db)
) -> Alert:
    """
    Flip the `is_read` flag.

    Idempotent: marking an already-read alert as read is a no-op that
    returns 200.
    """
    alert = _get_alert_or_404(db, alert_id)
    alert.is_read = payload.is_read
    db.commit()
    db.refresh(alert)
    return alert


@router.put(
    "/{alert_id}/resolve", response_model=AlertRead,
    summary="Mark an alert as resolved or reopen it",
 dependencies=[Depends(require_role('owner', 'manager', 'staff'))],)
def resolve_alert(
    alert_id: int, payload: ResolveRequest, db: Session = Depends(get_db)
) -> Alert:
    """
    Set `is_resolved` and keep `resolved_at` consistent with it.

    The database CHECK constraint requires the two to move together:
    resolving stamps `resolved_at`, reopening clears it. Updating the flag
    on its own would raise IntegrityError.
    """
    alert = _get_alert_or_404(db, alert_id)

    alert.is_resolved = payload.is_resolved
    alert.resolved_at = (
        datetime.now(timezone.utc) if payload.is_resolved else None
    )

    db.commit()
    db.refresh(alert)
    return alert


@router.put(
    "/read-all", response_model=Message,
    summary="Mark every matching alert as read",
 dependencies=[Depends(require_role('owner', 'manager', 'staff'))],)
def mark_all_read(
    db: Session = Depends(get_db),
    store_id: int | None = Query(None, gt=0),
    alert_type: str | None = Query(None, pattern=ALERT_TYPE_PATTERN),
) -> Message:
    """Bulk mark-as-read. Optional filters keep the action scoped."""
    filters = [Alert.is_read.is_(False)]
    if store_id is not None:
        filters.append(Alert.store_id == store_id)
    if alert_type is not None:
        filters.append(Alert.alert_type == alert_type)

    updated = (
        db.query(Alert).filter(*filters)
        .update({Alert.is_read: True}, synchronize_session=False)
    )
    db.commit()
    return Message(message=f"{updated} alerts marked as read")


@router.delete(
    "/{alert_id}", status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete an alert",
 dependencies=[Depends(require_role('owner', 'manager'))],)
def delete_alert(alert_id: int, db: Session = Depends(get_db)) -> None:
    """Delete an alert. Nothing references the alerts table, so this succeeds."""
    alert = _get_alert_or_404(db, alert_id)
    db.delete(alert)
    db.commit()