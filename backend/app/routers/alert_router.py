"""
Read + workflow router for alerts (B3 - SQL Server Stored Procedure).

Alerts are generated by `sp_Alerts_Generate`, so this router does not accept
POST. What it exposes is the work a user performs on an alert: mark it read
and mark it resolved. `sp_Alerts_Resolve` keeps `resolved_at` consistent with
`is_resolved`, which the CHECK constraint requires.
"""

import asyncio

from fastapi import APIRouter, Depends, HTTPException, Query, status
from pyodbc import Error as PyodbcError

from app.database import DbSession, get_db, map_sqlserver_error
from app.dependencies import require_role
from app.schemas.alert_schema import AlertPage, MarkReadRequest, ResolveRequest
from app.schemas.common import Message
from app.sp_helpers import as_bit, attach_product, attach_store
from app.websocket_manager import manager

router = APIRouter(prefix="/alerts", tags=["alerts"])

ALERT_TYPE_PATTERN = "^(expiring_soon|expired|low_stock|over_stock|forecast_anomaly)$"
SEVERITY_PATTERN = "^(low|medium|high|critical)$"
SEVERITY_ORDER = ["critical", "high", "medium", "low"]


def _to_read(row: dict) -> dict:
    row = dict(row)
    attach_store(row)
    attach_product(row)
    return row


def _paginate(
    db: DbSession,
    page: int,
    page_size: int,
    *,
    store_id: int | None = None,
    product_id: int | None = None,
    alert_type: str | None = None,
    severity: str | None = None,
    is_read: bool | None = None,
    is_resolved: bool | None = None,
) -> AlertPage:
    sets = db.call(
        "sp_Alerts_List",
        {
            "StoreId": store_id,
            "ProductId": product_id,
            "AlertType": alert_type,
            "Severity": severity,
            "IsRead": as_bit(is_read),
            "IsResolved": as_bit(is_resolved),
            "Page": page,
            "PageSize": page_size,
        },
    )
    total = int(sets[0][0]["total"]) if sets and sets[0] else 0
    items = [_to_read(row) for row in (sets[1] if len(sets) > 1 else [])]
    pages = (total + page_size - 1) // page_size
    return AlertPage(
        total=total, page=page, page_size=page_size, pages=pages, items=items
    )


def _get_or_404(db: DbSession, alert_id: int) -> dict:
    row = db.one("sp_Alerts_Get", {"AlertId": alert_id})
    if row is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Alert {alert_id} not found",
        )
    return row


# NOTE: `/unread` and `/unread-count` must be declared BEFORE `/{alert_id}`.
@router.get("/unread", response_model=AlertPage, summary="Unread alerts")
def list_unread_alerts(
    db: DbSession = Depends(get_db),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
    store_id: int | None = Query(None, gt=0),
    alert_type: str | None = Query(None, pattern=ALERT_TYPE_PATTERN),
    severity: str | None = Query(None, pattern=SEVERITY_PATTERN),
) -> AlertPage:
    try:
        return _paginate(
            db, page, page_size,
            store_id=store_id, alert_type=alert_type, severity=severity,
            is_read=False,
        )
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc


@router.get("/unread-count", summary="Count unread alerts")
def unread_count(
    db: DbSession = Depends(get_db),
    store_id: int | None = Query(None, gt=0),
    severity: str | None = Query(None, pattern=SEVERITY_PATTERN),
) -> dict:
    """Unread total plus a per-severity breakdown for the notification badge."""
    try:
        sets = db.call(
            "sp_Alerts_UnreadCount",
            {"StoreId": store_id, "Severity": severity},
        )
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc

    total = int(sets[0][0]["total"]) if sets and sets[0] else 0
    by_severity = {name: 0 for name in SEVERITY_ORDER}
    for row in (sets[1] if len(sets) > 1 else []):
        by_severity[row["severity"]] = int(row["total"])
    return {"total": total, "by_severity": by_severity}


@router.get("", response_model=AlertPage, summary="List alerts")
def list_alerts(
    db: DbSession = Depends(get_db),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
    store_id: int | None = Query(None, gt=0),
    product_id: int | None = Query(None, gt=0),
    alert_type: str | None = Query(None, pattern=ALERT_TYPE_PATTERN),
    severity: str | None = Query(None, pattern=SEVERITY_PATTERN),
    is_read: bool | None = Query(None),
    is_resolved: bool | None = Query(None),
) -> AlertPage:
    try:
        return _paginate(
            db, page, page_size,
            store_id=store_id, product_id=product_id, alert_type=alert_type,
            severity=severity, is_read=is_read, is_resolved=is_resolved,
        )
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc


@router.get("/{alert_id}", summary="Get one alert")
def get_alert(alert_id: int, db: DbSession = Depends(get_db)) -> dict:
    try:
        return _to_read(_get_or_404(db, alert_id))
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc


@router.put(
    "/{alert_id}/read", summary="Mark an alert as read or unread",
    dependencies=[Depends(require_role("owner", "manager", "staff"))],
)
def mark_read(
    alert_id: int, payload: MarkReadRequest, db: DbSession = Depends(get_db)
) -> dict:
    try:
        row = db.one(
            "sp_Alerts_MarkRead",
            {"AlertId": alert_id, "IsRead": as_bit(payload.is_read)},
        )
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc
    return _to_read(row)


@router.put(
    "/{alert_id}/resolve", summary="Mark an alert as resolved or reopen it",
    dependencies=[Depends(require_role("owner", "manager", "staff"))],
)
def resolve_alert(
    alert_id: int, payload: ResolveRequest, db: DbSession = Depends(get_db)
) -> dict:
    try:
        row = db.one(
            "sp_Alerts_Resolve",
            {
                "AlertId": alert_id,
                "IsResolved": as_bit(payload.is_resolved),
                "Note": payload.note,
            },
        )
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc
    alert_data = _to_read(row)
    try:
        asyncio.create_task(
            manager.broadcast(
                {
                    "type": "alert_updated",
                    "alert": alert_data,
                    "message": "Canh bao da duoc cap nhat",
                }
            )
        )
    except Exception:
        pass
    return alert_data


@router.put(
    "/read-all", response_model=Message,
    summary="Mark every matching alert as read",
    dependencies=[Depends(require_role("owner", "manager", "staff"))],
)
def mark_all_read(
    db: DbSession = Depends(get_db),
    store_id: int | None = Query(None, gt=0),
    alert_type: str | None = Query(None, pattern=ALERT_TYPE_PATTERN),
) -> Message:
    try:
        updated = db.scalar(
            "sp_Alerts_MarkAllRead",
            {"StoreId": store_id, "AlertType": alert_type},
            column="updated",
        )
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc
    return Message(message=f"{updated or 0} alerts marked as read")


@router.delete(
    "/{alert_id}", status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete an alert",
    dependencies=[Depends(require_role("owner", "manager"))],
)
def delete_alert(alert_id: int, db: DbSession = Depends(get_db)) -> None:
    try:
        db.call("sp_Alerts_Delete", {"AlertId": alert_id})
    except PyodbcError as exc:
        raise map_sqlserver_error(exc) from exc
    try:
        asyncio.create_task(
            manager.broadcast(
                {
                    "type": "alert_deleted",
                    "alert_id": alert_id,
                    "message": "Canh bao da duoc xoa",
                }
            )
        )
    except Exception:
        pass
    return None
